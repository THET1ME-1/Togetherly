import 'dart:convert';

import 'package:crypto/crypto.dart';

/// Id записи штриха на сервере. Считает его телефон, а не сервер (TOG-12).
///
/// Пока id выдавал сервер, повтор создания после таймаута или 502 заводил
/// вторую запись того же мазка: очередь считает операцию проваленной по своему
/// пределу в 20 секунд, а запрос к этому моменту уже лёг в базу. На раскрасках
/// с 19 по 22 октября 2026 нашлось 187 мазков в 2–12 копиях. Ластик и отмена
/// снимали одну копию, остальные оставались, и стёртое «возвращалось».
///
/// С id из номера мазка повтор упирается в «уже есть», а отмена знает, какую
/// запись удалить, ещё до ответа сервера. Пара и холст входят в хеш, чтобы
/// одинаковые номера на разных холстах не столкнулись.
String strokeRecordId(String groupId, String canvasId, String clientId) {
  final digest =
      sha256.convert(utf8.encode('$groupId|$canvasId|$clientId')).toString();
  return 's${digest.substring(0, 14)}';
}

final RegExp _recordId = RegExp(r'^[a-z0-9]{15}$');

/// true — это id записи, который годится серверу, а не номер мазка вида
/// `local_…`, `fill_…`. Операции очереди от прежних версий несут номер мазка:
/// его серверу не отдаём, id тогда выдаёт сервер, как раньше.
bool isStrokeRecordId(String id) => _recordId.hasMatch(id);
