/// Раскладка виджета «Скучаю»: кегль числа и его запись.
///
/// Счёт у пары растёт быстро — тысяча импульсов за пару месяцев обычное дело,
/// — а кегль в виджете был прибит гвоздями. На снимке 20.09.2026 «1000»
/// разорвалось на две строки: «100» и «0» под ним.
///
/// Числа рисуются в трёх местах (Kotlin, Swift, превью каталога), поэтому
/// правило живёт здесь, а сторож `test/models/miss_widget_spec_test.dart`
/// сверяет его с нативом.
library;

/// Кегль числа под ширину плитки: чем больше знаков, тем мельче.
///
/// [base] — кегль однозначного числа: он свой у каждого размера виджета.
/// Ниже 16 не опускаемся: мельче цифра перестаёт читаться с расстояния
/// вытянутой руки, а плитка всё равно шире.
double missCountSize(int count, {required double base}) {
  final digits = count.abs().toString().length;
  final size = switch (digits) {
    <= 2 => base,
    3 => base * 0.86,
    4 => base * 0.74,
    _ => base * 0.62,
  };
  return size < 16 ? 16 : size;
}

/// Как число пишется на плитке.
///
/// До десяти тысяч — как есть: человеку важна точная цифра, он её копит.
/// Дальше сокращаем, иначе даже ужатый кегль упрётся в край.
String missCountText(int count) {
  final n = count < 0 ? 0 : count;
  if (n < 10000) return '$n';
  if (n < 1000000) return '${_short(n / 1000)}K';
  return '${_short(n / 1000000)}M';
}

/// Одна цифра после запятой, и та отбрасывается у круглых значений.
String _short(double v) {
  final rounded = (v * 10).round() / 10;
  if (rounded == rounded.roundToDouble()) return '${rounded.round()}';
  return rounded.toStringAsFixed(1).replaceAll('.', ',');
}
