/// Накопитель нажатий «Скучаю».
///
/// Каждый тап уходил своим запросом, и человек, нажимающий подряд, упирался в
/// ограничитель сервера: 523 отказа 429 за сутки на `/api/group/miss-you`.
/// Лимит там щедрый (600 запросов за 10 секунд), но считается он по адресу, а
/// за одним мобильным адресом сидят сотни пар — отсюда «половину нажатий не
/// регистрирует» (жалоба с iPhone, 13 августа 2026).
///
/// Теперь частые нажатия копятся и уходят одним запросом с числом. Сердечки и
/// отклик кнопки остаются мгновенными: они рисуются на месте, не дожидаясь
/// сервера.
class MissYouBatch {
  /// Сколько нажатий уходит за одну отправку. Больше двадцати за раз — это уже
  /// не «скучаю», а зажатый палец.
  static const int maxPerSend = 20;

  int _pending = 0;

  /// Сколько нажатий ждёт отправки.
  int get pending => _pending;

  /// Записать нажатие. Возвращает накопленное число.
  int add() => ++_pending;

  /// Забрать накопленное для отправки. Остаток сверх предела остаётся в
  /// накопителе и уйдёт следующим запросом.
  int take() {
    if (_pending <= 0) return 0;
    final send = _pending > maxPerSend ? maxPerSend : _pending;
    _pending -= send;
    return send;
  }

  /// Забрать ВСЁ накопленное, разложив по пачкам не больше [maxPerSend].
  ///
  /// Нужен на выходе — когда экран закрывается или приложение уходит в фон.
  /// Обычный [take] отдаёт одну пачку, и остаток оставался в памяти навсегда:
  /// человек лупил по сердцу, свернул приложение и увидел счёт меньше, чем
  /// был на экране (скринкаст 16.08.2026, 6687 → 6670 — потерялось 17 тапов).
  List<int> takeAllChunks() {
    final chunks = <int>[];
    while (_pending > 0) {
      chunks.add(take());
    }
    return chunks;
  }

  /// Вернуть нажатия в накопитель: отправка не дошла, а терять их нельзя.
  void giveBack(int count) {
    if (count > 0) _pending += count;
  }
}
