/// Догрузка кода комнаты совместного просмотра.
///
/// Код спрашивался ровно один раз, при открытии экрана. Этого мало: сессия
/// PocketBase к первому кадру бывает ещё не поднята, id пары приезжает позже,
/// а вечером сервер отвечает дольше клиентского таймаута. Любой из трёх
/// случаев оставлял человека с многоточием в строке «Партнёр смотрит в
/// браузере?» и мёртвой кнопкой копирования — жалоба со снимком 16.08.2026,
/// заведённая как «нет кода».
///
/// Повторяем, но считанное число раз и с растущей паузой: бесконечный круг
/// запросов — ровно то, чем клиент валил сервер в августе (см. `UpsertBackoff`).
library;

/// Сколько всего попыток делаем, прежде чем показать прочерк.
const int watchRoomMaxAttempts = 4;

/// Нужен ли ещё один заход после попытки номер [attempt] (с нуля).
bool watchRoomShouldRetry({required String code, required int attempt}) =>
    code.isEmpty && attempt < watchRoomMaxAttempts;

/// Пауза перед попыткой номер [attempt] + 1.
///
/// Первая короткая — человек в этот момент смотрит на экран и ждёт код.
/// Дальше вдвое, с потолком: сервер под нагрузкой не надо добивать.
Duration watchRoomRetryDelay(int attempt) {
  final capped = attempt < 0 ? 0 : (attempt > 5 ? 5 : attempt);
  final seconds = 1 << capped; // 1, 2, 4, 8, 16, 32
  return Duration(seconds: seconds > 30 ? 30 : seconds);
}
