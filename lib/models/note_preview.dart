/// Что показать на превью заметки в каталоге виджетов.
///
/// Жалоба 20.09.2026: «Текст на заметке в приложении не меняется». И не мог:
/// в превью был зашит образец про молоко, а настоящая заметка живёт в ключе
/// `note_<группа>_text` и до карточки не доходила.
///
/// Пустую заметку образцом всё же подменяем: пустой листик в каталоге читается
/// как сломанный виджет, а человек ещё ничего не писал.
String notePreviewText(String saved, {required String demo}) {
  final text = saved.trim();
  return text.isEmpty ? demo : text;
}
