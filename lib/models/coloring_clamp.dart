/// Прижатие мазка к своей половине листа в раскраске вдвоём.
///
/// Лист делится пополам, и чужая половина касаний не принимает; мазок у центра
/// прижимается к своей стороне, чтобы линия не обрывалась на полуслове.
///
/// Границы считались прямо на месте — `half - margin` и `half + margin`, где
/// отступ зависит от толщины кисти. Толстая кисть на узком листе переворачивала
/// диапазон, и `clamp` бросал `ArgumentError` прямо из обработчика движения
/// пальца: приложение вылетало посреди мазка. То же самое давал лист, который
/// ещё не измерен (ширина ноль). Отсюда отзыв «часто вылетает в раскрасках»
/// (16.08.2026).
library;

/// Куда попадает точка [x] после прижатия к своей половине.
///
/// [width] — ширина листа, [strokeWidth] — толщина кисти, [left] — своя
/// половина левая. Ширина нулевая (лист ещё не измерен) означает, что делить
/// нечего: точка возвращается как есть.
double coloringClampX(
  double x, {
  required double width,
  required double strokeWidth,
  required bool left,
}) {
  if (width <= 0) return x;

  final half = width / 2;
  // Отступ от середины на радиус кисти, чтобы мазок не вылезал на чужую
  // половину. Больше половины он быть не может: иначе своей стороны не
  // остаётся вовсе, а границы переворачиваются.
  final margin = (strokeWidth / 2 + 1).clamp(0.0, half);

  final low = left ? 0.0 : half + margin;
  final high = left ? half - margin : width;
  // Порядок границ страхуем и здесь: считать их — одно, доверять — другое.
  if (high < low) return half;
  return x.clamp(low, high);
}
