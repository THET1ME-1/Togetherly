/// Ждёт ли пара своего человека на самом деле.
///
/// Флага с сервера мало. Партнёр входит и обычным кодом приглашения, а тот
/// путь `waiting_mode` не гасил: участников двое, а пара считалась ждущей.
/// Экран связи показывал «Ждём человека» поверх живой пары, и выйти оттуда
/// было нельзя — «Больше не жду» сервер отбивал, потому что место занято.
///
/// Правило простое: ждут, пока место пусто.
bool waitingIsActive({required bool flag, required int partners}) =>
    flag && partners == 0;
