/// Когда считать, что полноэкранная реклама закрылась.
///
/// SDK обещает событие закрытия, но не всегда его присылает: по журналу
/// 9528 показов закончились «награды нет», и человек сидел на этом экране
/// 120 секунд медианы — упирался в предохранитель на две минуты. Ни одного
/// случая «закрыл сам»: люди досматривали ролик и ждали. Вход в совместный
/// просмотр всё это время стоял, и жалоба звучала как «посмотрел рекламу и
/// ничего, в комнату не перекидывает».
///
/// Закрытие видно и без SDK: полноэкранная реклама уводит приложение с
/// переднего плана, а её конец — это возврат.
library;

import 'package:flutter/widgets.dart';

/// Общий предохранитель ожидания.
///
/// Ролики у сетей идут до шестидесяти секунд; дольше человек уже считает,
/// что приложение зависло.
const Duration kAdShowGuard = Duration(seconds: 70);

/// Сколько ждём после возврата, прежде чем закрыть ожидание.
///
/// Событие закрытия от SDK часто приходит следом за возвратом — даём ему
/// долететь, чтобы награда успела засчитаться штатным путём.
const Duration kAdReturnGrace = Duration(milliseconds: 600);

/// Сколько после ролика ждём ответа сервера о начислении.
///
/// Вызывающий экран в это время держит спиннер; ответ, потерянный по
/// дороге, без предела держал бы его вечно.
const Duration kAdGrantWait = Duration(seconds: 10);

/// Сколько ждём, пока SDK примет сам вызов показа.
///
/// Вызов возвращается сразу, как только SDK начал показ; не вернулся —
/// ожидание закрытия всё равно отпустит экран своим предохранителем.
const Duration kAdShowStart = Duration(seconds: 15);

/// Сколько ждать, пока человек закроет показанную рекламу. Он мог отложить
/// телефон и забыть про неё: награда всё равно его.
const Duration kAdShownWait = Duration(minutes: 30);

/// Заслужена ли награда, когда `onRewarded` так и не пришёл.
///
/// Решение владельца 20.10.2026: реклама показана и закрылась — награда
/// положена, сколько бы ни шла и когда бы её ни закрыли. Прежние пороги
/// (не короче 15 секунд, не дольше 5–10 минут) отнимали награду у тех, кто
/// пролистал пачку роликов или отложил телефон, а событие награды Яндекс
/// присылает не всегда. Сутки держит серверный предел начислений.
///
/// [shown] — пришло ли `onAdShown`: без него человек ролика не видел вовсе.
/// [away] и [onScreen] остаются для отчёта в Bugsink.
bool adRewardDeserved({
  required bool shown,
  required Duration away,
  required Duration onScreen,
}) {
  return shown;
}

/// Следит за уходом и возвращением приложения во время показа.
class AdShowWatch {
  bool _left = false;
  bool _finished = false;
  DateTime? _leftAt;
  Duration _away = Duration.zero;

  /// Приложение уходило с переднего плана и вернулось.
  bool get finished => _finished;

  /// Сколько приложение простояло за рекламой.
  ///
  /// Меряется по переходам жизненного цикла, а не по стенным часам с начала
  /// показа: последние включают и то время, что человек провёл вне ролика.
  Duration get away => _away;

  /// Приложение отдало экран рекламе: сейчас под ней или уже вернулось.
  ///
  /// Это доказательство показа, когда Яндекс не прислал `onAdShown`
  /// (эмулятор 20.10.2026: реклама шла две минуты, события не было).
  bool get sawAd => _left || _leftAt != null;

  void onState(AppLifecycleState state, {DateTime? at}) {
    final now = at ?? DateTime.now();
    switch (state) {
      case AppLifecycleState.paused:
      case AppLifecycleState.hidden:
      case AppLifecycleState.detached:
        _leftAt ??= now;
        _left = true;
      case AppLifecycleState.resumed:
        final since = _leftAt;
        // Долгая потеря фокуса — это полупрозрачная реклама поверх нас.
        if (!_left && since != null && now.difference(since) >= kAdInactiveIsAd) {
          _left = true;
        }
        if (_left) {
          _finished = true;
          if (since != null) _away += now.difference(since);
        }
        _leftAt = null;
      // Яндекс на Android показывает рекламу полупрозрачным окном: приложение
      // под ним не уходит в фон, а только теряет фокус. Короткое мигание
      // (шторка, звонок) уходом не считается — решает длительность.
      case AppLifecycleState.inactive:
        _leftAt ??= now;
    }
  }
}

/// Сколько приложение должно простоять без фокуса, чтобы это была реклама,
/// а не шторка уведомлений.
const Duration kAdInactiveIsAd = Duration(seconds: 3);

/// Сколько ждать закрытия рекламы.
///
/// Пока SDK не сказал «показано», хватает [kAdShowGuard]: показ мог не
/// начаться вовсе. Показанная реклама ждёт своего закрытия до
/// [kAdShownWait]: Яндекс крутит пачки из трёх роликов дольше 70 секунд,
/// и прежний предохранитель решал «закрылась» посреди пачки (20.10.2026,
/// эмулятор): сундук открывался под рекламой, а «Ролик не засчитан» выходил
/// поверх неё.
Duration adCloseWaitLimit({required bool shown}) => shown ? kAdShownWait : kAdShowGuard;
