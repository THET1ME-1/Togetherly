/// Когда считать, что полноэкранная реклама закрылась.
///
/// SDK обещает событие закрытия, но не всегда его присылает: по журналу
/// 9528 показов закончились «награды нет», и человек сидел на этом экране
/// 120 секунд медианы — упирался в предохранитель на две минуты. Ни одного
/// случая «закрыл сам»: люди досматривали ролик и ждали. Вход в совместный
/// просмотр всё это время стоял, и жалоба звучала как «посмотрел рекламу и
/// ничего, в комнату не перекидывает».
///
/// Закрытие видно и без SDK: полноэкранная реклама уводит приложение с
/// переднего плана, а её конец — это возврат.
library;

import 'package:flutter/widgets.dart';

/// Общий предохранитель ожидания.
///
/// Ролики у сетей идут до шестидесяти секунд; дольше человек уже считает,
/// что приложение зависло.
const Duration kAdShowGuard = Duration(seconds: 70);

/// Сколько ждём после возврата, прежде чем закрыть ожидание.
///
/// Событие закрытия от SDK часто приходит следом за возвратом — даём ему
/// долететь, чтобы награда успела засчитаться штатным путём.
const Duration kAdReturnGrace = Duration(milliseconds: 600);

/// Следит за уходом и возвращением приложения во время показа.
class AdShowWatch {
  bool _left = false;
  bool _finished = false;

  /// Приложение уходило с переднего плана и вернулось.
  bool get finished => _finished;

  void onState(AppLifecycleState state) {
    switch (state) {
      case AppLifecycleState.paused:
      case AppLifecycleState.hidden:
      case AppLifecycleState.detached:
        _left = true;
      case AppLifecycleState.resumed:
        if (_left) _finished = true;
      // Мигание inactive даёт шторка уведомлений и входящий звонок — уходом
      // это не считается.
      case AppLifecycleState.inactive:
        break;
    }
  }
}
