/// Выход по двойному «назад»: первое нажатие предупреждает, второе выпускает.
///
/// Просьба пары (20.09.2026): «случайно нажимаешь и тебя выбрасывает с
/// комнаты». Выход из комнаты совместного просмотра стоит дорого — кино
/// останавливается у обоих, и вернуться значит заново искать место.
///
/// Подтверждение листом тут хуже: его пришлось бы закрывать каждый раз, когда
/// человек выходит нарочно, а выходят чаще, чем промахиваются.
library;

/// Сколько живёт первое нажатие.
const Duration kExitWindow = Duration(seconds: 3);

/// Выпускать ли по нажатию «назад».
///
/// [lastPress] — когда нажали в прошлый раз; `null` — не нажимали.
/// Часы, прыгнувшие назад (перевод времени, синхронизация), не должны запирать
/// человека в комнате, поэтому отрицательная разница считается новым нажатием.
bool exitOnBack({required DateTime? lastPress, required DateTime now}) {
  if (lastPress == null) return false;
  final passed = now.difference(lastPress);
  if (passed.isNegative) return false;
  return passed <= kExitWindow;
}
