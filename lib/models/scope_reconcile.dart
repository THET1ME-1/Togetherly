/// Когда сверять состав области с сервером.
///
/// Инкрементальная синхронизация тянет то, у чего вырос `updated`, и удалённой
/// строки в такой выборке нет вовсе. Воспоминания удаляются насовсем (очередь
/// шлёт `hard: true`, надгробий на проде ноль), поэтому пропущенное событие
/// `delete` — например, у телефона без живого сокета — навсегда оставляет
/// запись в его кэше. Лечится только сверкой состава: что есть на сервере, то
/// и остаётся в кэше.
library;

/// Пауза между сверками одной области.
///
/// Шесть часов: сверка тянет список записей области целиком, и делать это на
/// каждый заход в ленту — лишний трафик у всех ради редкого случая.
const int kScopeReconcileGapMs = 6 * 3600 * 1000;

/// Пора ли сверять область.
///
/// Отметка из будущего (часы телефона перевели назад) считается свежей: иначе
/// она означала бы «сверять каждый раз».
bool mayReconcileScope({required int nowMs, required int lastAtMs}) {
  if (lastAtMs <= 0) return true;
  if (lastAtMs > nowMs) return false;
  return nowMs - lastAtMs >= kScopeReconcileGapMs;
}
