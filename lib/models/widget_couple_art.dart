/// Картинка пары в виджете «Дни вместе» и правило записи пола.
///
/// Рисунок выбирает натив (Kotlin и Swift одинаково), но решает всё пара
/// значений `days_<группа>_my_gender` и `days_<группа>_partner_gender`. Пустое
/// значение там значащее: оно НЕ считается «не знаю», а просто не совпадает ни
/// с `female`, ни с `male`, и рисуется пара «парень и девушка».
///
/// Отсюда жалоба 29.08.2026 с двух айфонов: «у обеих пол женский, а на экране
/// появляется мальчик». Пол уходил в ключи из кэша сервиса, а `syncTimerAndDays`
/// зовётся и до того, как кэш заполнен, — верное значение затиралось пустым. На
/// Android это чинилось следующим фоновым обновлением, на iPhone фонового
/// обновления нет вовсе, и пустота доживала до перезапуска приложения.
library;

/// Имя картинки пары. Повторяет ветку натива один в один — держим её здесь,
/// чтобы правило можно было проверить тестом, а не глазами на телефоне.
String coupleArtFor(String myGender, String partnerGender) {
  if (myGender == 'female' && partnerGender == 'female') return 'widget_couple_ff';
  if (myGender == 'male' && partnerGender == 'male') return 'widget_couple_mm';
  return 'widget_couple_mf';
}

/// Стоит ли класть это значение в ключ виджета.
///
/// Пустым не затираем: лучше оставить прежний верный пол, чем нарисовать паре
/// из двух девушек мальчика.
bool shouldWriteGender(String value) => value.isNotEmpty;
