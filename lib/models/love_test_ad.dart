/// Правило показа ролика перед результатом теста «Умение любить».
///
/// Решение владельца от 20.08.2026: результат открывается после видео, и
/// пропустить показ нельзя. Кнопку закрытия внутри самого ролика рисует
/// рекламная сеть — это её правило, и обойти его нечем; наше дело в том,
/// чтобы показ случился.
///
/// Правило вынесено из экрана, потому что оно про поведение, а не про
/// раскладку: три исключения тут важнее самого показа.
library;

/// Сколько молчим после показанного ролика.
///
/// Тест проходят раундами, и человек, ответивший на двадцать утверждений,
/// иногда тут же берётся за следующий заход. Две рекламы подряд и AdMob, и
/// Яндекс считают недобросовестным трафиком — за это снимают аккаунт, а не
/// показ.
const Duration kLoveAdCooldown = Duration(minutes: 30);

/// Крутить ли ролик перед фигурой.
///
/// [plusActive] — у оплатившего Togetherly+ рекламы нет нигде, как и в ленте
/// (`ad_banner.dart`). [adReady] — ролик уже загружен: незагруженный ждать
/// нельзя, иначе человек смотрит в пустой экран вместо результата (ровно так
/// замирал совместный просмотр 12.08.2026). [lastShownMs] — когда крутили в
/// прошлый раз, ноль означает «ни разу».
bool showAdBeforeLoveResult({
  required bool plusActive,
  required bool adReady,
  required int lastShownMs,
  required int nowMs,
}) {
  if (plusActive) return false;
  if (!adReady) return false;
  if (lastShownMs <= 0) return true;
  final passed = nowMs - lastShownMs;
  // Отметка из будущего — часы телефона перевели назад. Считаем, что пауза
  // прошла: иначе показ заблокируется до тех пор, пока время не догонит метку.
  if (passed < 0) return true;
  return passed >= kLoveAdCooldown.inMilliseconds;
}
