/// Когда показывать межстраничную рекламу после комнаты совместного просмотра.
///
/// До 19.10.2026 перед комнатой стоял обязательный ролик за награду. Браузер
/// комнаты на iPhone рождался под уходящей рекламой и терял касания: замер
/// Umami 19.10 дал 45% заходов без единого касания после ролика против 9% без
/// него. Теперь ролик идёт после выхода, блоком «Совместный просмотр».
library;

import 'dart:ui' show AppLifecycleState;

/// С Плюсом рекламы нет. Ленты пускают и выпускают без неё (решение
/// 04.10.2026). Приложению не на экране показывать нельзя: сети запрещают
/// рекламу вне приложения.
bool roomExitAdDue({
  required bool plus,
  required bool reels,
  required AppLifecycleState? lifecycle,
}) =>
    !plus && !reels && lifecycle == AppLifecycleState.resumed;
