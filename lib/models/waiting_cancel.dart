/// Чем закончилась попытка выйти из режима ожидания.
enum WaitingCancelOutcome {
  /// Сервер снял ожидание — пары больше нет.
  cancelled,

  /// Ждать уже некого: партнёр вошёл по коду, или ожидание сняли раньше.
  /// Для человека это тот же результат — карточка уходит с экрана.
  alreadyPaired,

  /// Не дошло: сеть, отказ сервера, что-то ещё. Стоит повторить.
  failed,
}

/// Как понимать ответ `/api/waiting/cancel`.
///
/// Сервер отвечает отказом не только на поломку. Пока человек смотрел на
/// карточку «Ждём человека», партнёр мог ввести код — тогда режим ожидания
/// снят, и на «Больше не жду» приходит «Место уже занято». Приложение
/// показывало это ошибкой, человек жал снова и снова: шесть отказов за одну
/// секунду от одного человека в журнале 18.08.2026, и жалоба «разорвать
/// ожидание не получается».
///
/// Ждать в этом состоянии действительно некого, поэтому такой ответ для нас —
/// успех: карточку убираем, состояние пары перечитываем. Настоящая ошибка —
/// только та, где сервер не сказал ничего внятного.
WaitingCancelOutcome waitingCancelOutcome({
  required bool ok,
  required String message,
}) {
  if (ok) return WaitingCancelOutcome.cancelled;
  final text = message.toLowerCase();
  const settled = [
    'место уже занято',
    'пара не найдена',
    'already',
    'not found',
  ];
  for (final mark in settled) {
    if (text.contains(mark)) return WaitingCancelOutcome.alreadyPaired;
  }
  return WaitingCancelOutcome.failed;
}
