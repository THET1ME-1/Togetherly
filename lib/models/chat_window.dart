/// Окно ленты чата: какие сообщения из кэша рисовать.
///
/// Кэш телефона копит всю просмотренную переписку пары, и поток отдавал её
/// ленте целиком — у живой пары тысячи сообщений. Прыжок вниз при открытии
/// чата раскладывал каждый ряд и выбрасывал их разом, на слабых Android это
/// окно «приложение не отвечает» (жалоба 16.11.2026).
///
/// Лента берёт новейшие [limit] сообщений и всё, что не старше [floorTs] —
/// начала окна, уже стоящего на экране. Без границы новое сообщение сдвигало
/// бы окно на одну строку, и каждый пузырь перестраивался бы заново.
/// [asc] отсортирован по времени от старых к новым.
List<T> chatWindow<T>(
  List<T> asc, {
  required int limit,
  required int? floorTs,
  required int Function(T) tsOf,
}) {
  var start = asc.length > limit ? asc.length - limit : 0;
  if (floorTs != null) {
    // Первое сообщение не старше границы: всё от него остаётся на экране.
    var i = start;
    while (i > 0 && tsOf(asc[i - 1]) >= floorTs) {
      i--;
    }
    start = i;
  }
  return start == 0 ? asc : asc.sublist(start);
}
