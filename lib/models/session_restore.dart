/// Полумёртвая сессия и как из неё выбираться.
///
/// `AsyncAuthStore` из SDK при восстановлении кладёт в стор `RecordModel
/// .fromJson({})`, если сохранённой записи не оказалось: токен живой,
/// `authStore.isValid` true, запросы авторизуются — а профиля нет. Приложение
/// в этом состоянии не знает своего имени и аватара, поэтому вместо фотографии
/// рисуется буква, а срок пары считается не от той даты.
///
/// Само оно не проходит: `signInSilently` зовётся один раз за запуск, и если
/// его `authRefresh` не уложился в свои восемь секунд (медленная сеть на
/// старте — обычное дело), человек сидит так до перезапуска приложения.
/// Лечилось выходом и повторным входом — это и была жалоба 19 августа 2026.
library;

/// Сколько молчим между попытками дотянуть профиль.
///
/// Полминуты: чаще — наплыв одинаковых запросов со всех телефонов, у которых
/// сервер в этот момент и без того не отвечает; реже — человек слишком долго
/// смотрит на букву вместо своего лица.
const int kProfileRestoreGapMs = 30 * 1000;

/// Нужно ли дотягивать профиль текущего человека.
///
/// [hasSession] — есть ли живой токен, [recordId] — id записи из `authStore`.
bool needsProfileRestore({
  required bool hasSession,
  required String? recordId,
}) {
  if (!hasSession) return false;
  return recordId == null || recordId.isEmpty;
}

/// Пора ли повторять попытку.
///
/// Отметка из будущего (часы телефона перевели назад) считается свежей: иначе
/// она означала бы «пробовать каждый раз».
bool mayRetryProfileRestore({required int nowMs, required int lastTryMs}) {
  if (lastTryMs <= 0) return true;
  if (lastTryMs > nowMs) return false;
  return nowMs - lastTryMs >= kProfileRestoreGapMs;
}
