/// Где в ленте воспоминаний стоят баннеры.
///
/// Первый — сразу после первого воспоминания, дальше через каждые
/// [kAdEveryNMemories]. Прежде первые шесть карточек шли без рекламы вовсе, и
/// до первого баннера долистывали не все: в РСЯ на 4,9 тысячи запросов
/// приходилось 1,5 тысячи показов. Запрос уходит при создании виджета, а показ
/// засчитывается только когда баннер побывал на экране, поэтому первый баннер
/// надо ставить там, где человек точно окажется.
library;

/// Через сколько воспоминаний повторяется баннер.
///
/// Плотнее ставить нельзя: и AdMob, и Яндекс считают слишком частую рекламу
/// недобросовестным трафиком, а лента у пары своя, не витрина.
const int kAdEveryNMemories = 6;

/// Ставить ли баннер после воспоминания с порядковым номером [position]
/// (нумерация с единицы, счёт сквозной по всей ленте, а не внутри дня).
bool adAfterMemory(int position) {
  if (position < 1) return false;
  return (position - 1) % kAdEveryNMemories == 0;
}
