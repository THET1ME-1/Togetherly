/// Что снимет отмена: последний штрих или последнюю правку формы.
///
/// На холсте два разных действия делят одну кнопку «отменить». Нарисованные
/// штрихи лежат своим стеком, правки выделенной фигуры — своим, и без общей
/// шкалы отмена сняла бы сперва все штрихи и только потом добралась до
/// перемещённого круга — то есть снесла бы работу, которую человек трогать не
/// просил.
///
/// Шкала — сквозной счётчик действий: у кого номер больше, тот и случился
/// позже. Отсутствие действия обозначается `null`.
bool undoTakesEdit({int? lastEditSeq, int? lastStrokeSeq}) {
  if (lastEditSeq == null) return false;
  if (lastStrokeSeq == null) return true;
  return lastEditSeq > lastStrokeSeq;
}
