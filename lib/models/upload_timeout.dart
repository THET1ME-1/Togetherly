/// Сколько ждать заливку файла и стоит ли повторять её после отказа.
///
/// Срок был жёстким — шестьдесят секунд на что угодно, — и за тридцать дней
/// 155 заливок оборвались, не дойдя до конца. Девяносто три из них картинки
/// холста: заливка ведром кладёт пятно целой картинкой, и на мобильной сети
/// мегабайты в минуту не укладываются. Ролику совместного просмотра (до 300 МБ
/// с Togetherly+) минуты не хватит тем более.
library;

/// Нижний порог: столько держим даже под крошечный файл.
///
/// Меньше нельзя — на плохой сети само рукопожатие занимает десятки секунд, а
/// оборванная заливка стоит человеку потерянного воспоминания.
const Duration kUploadTimeoutMin = Duration(seconds: 60);

/// Потолок: дольше человек считает, что приложение зависло.
const Duration kUploadTimeoutMax = Duration(minutes: 10);

/// Сколько времени даём на каждый мегабайт.
///
/// Пятнадцать секунд на мегабайт — это примерно 0,5 Мбит/с, то есть очень
/// медленный мобильный интернет. Быстрая сеть уложится задолго до срока.
const int kUploadSecondsPerMb = 15;

/// Срок заливки для файла в [bytes] байт.
Duration uploadTimeoutFor(int bytes) {
  if (bytes <= 0) return kUploadTimeoutMin;
  // Мегабайты считаем целыми: секунда прибавки под сорокакилобайтное
  // голосовое ничего не решает, а нижний порог перестаёт быть порогом.
  final mb = bytes ~/ (1024 * 1024);
  final seconds = kUploadTimeoutMin.inSeconds + mb * kUploadSecondsPerMb;
  if (seconds >= kUploadTimeoutMax.inSeconds) return kUploadTimeoutMax;
  return Duration(seconds: seconds);
}

/// Стоит ли повторять заливку после отказа с кодом [statusCode].
///
/// Повторяем то, что зависит от сети и от минуты: обрыв, молчание, прилёгший
/// сервер. Отказ по сути — протухшая сессия, запрет доступа, слишком большой
/// файл — со второй попытки тем же и останется, а повтор стоит человеку ещё
/// одной минуты ожидания и лишнего трафика.
bool uploadWorthRetry(int? statusCode) {
  if (statusCode == null) return true; // таймаут, обрыв, нет ответа
  if (statusCode == 408 || statusCode == 429) return true;
  return statusCode >= 500;
}
