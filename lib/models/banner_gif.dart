/// GIF в баннере профиля — одна из вещей Togetherly+.
///
/// Обычный баннер проходит кроп 16:9 и пересжатие в WebP, а после того и
/// другого от GIF остаётся первый кадр. Поэтому GIF уходит на сервер как есть,
/// без обрезки: в шапке его подгоняет `BoxFit.cover`, как любую картинку.
///
/// Шевелится он, пока у владельца открыт Плюс (`ProfileBanner.animate`), без
/// Плюса стоит первым кадром.
class BannerGif {
  const BannerGif._();

  /// Потолок файла.
  ///
  /// Баннер скачивает каждый, кто открыл профиль: сам человек и его пара, а за
  /// трафик бакета мы платим. Десяти мегабайт хватает на несколько секунд во
  /// всю ширину экрана, и скачанное ложится в постоянный кэш картинок —
  /// второй раз его не качают.
  static const int maxBytes = 10 * 1024 * 1024;

  /// Потолок в мегабайтах, для подписи.
  static int get maxMb => maxBytes ~/ (1024 * 1024);

  /// Сколько первых байт файла нужно [isGif].
  static const int headerLength = 6;

  /// Начинается ли файл с подписи GIF: «GIF87a» или «GIF89a».
  ///
  /// Расширению верить нельзя: пикер на Android берёт его из типа, который
  /// назвала система, а не назвала — оставляет чужое имя или ставит `.jpg`.
  /// Такой GIF ушёл бы в пересжатие WebP и застыл.
  static bool isGif(List<int> head) {
    if (head.length < headerLength) return false;
    return head[0] == 0x47 && // G
        head[1] == 0x49 && // I
        head[2] == 0x46 && // F
        head[3] == 0x38 && // 8
        (head[4] == 0x37 || head[4] == 0x39) && // 7 или 9
        head[5] == 0x61; // a
  }

  /// Влезает ли файл в потолок. Пустой не влезает: заливать нечего.
  static bool fits(int bytes) => bytes > 0 && bytes <= maxBytes;
}
