/// Карточка «партнёр прошёл „Умение любить“» на главной.
///
/// Появляется ровно в одном случае: партнёр ответил, а человек ещё нет — тогда
/// у него есть повод открыть тест и сравнить фигуры. Первое касание её
/// закрывает навсегда, всё равно каким: прошёл или смахнул. Напоминаний нет,
/// иначе карточка становится баннером, который висит на главной месяцами.
library;

bool showLovePrompt({
  required bool partnerDone,
  required bool mineDone,
  required bool dismissed,
}) =>
    partnerDone && !mineDone && !dismissed;
