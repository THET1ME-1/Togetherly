/// Стирает ли метка очистки из меты холста то, что уже на экране.
///
/// Очистка удаляет штрихи на сервере и пишет в мету новую метку. Экран стирает
/// у себя всё, только если метка сменилась, пока он открыт. Первая мета после
/// входа метку лишь запоминает: штрихи, нарисованные после той очистки, уже
/// пришли своим потоком, и стирать их нельзя. Раньше первая мета стирала
/// картинку всегда, и лист, который когда-то чистили, при повторном входе
/// открывался пустым, если штрихи успевали прийти раньше меты (обращение 294).
///
/// [metaSeen] — мета этого холста уже приходила, [seen] — запомненная метка,
/// [incoming] — метка из пришедшей меты.
bool clearWipesCanvas({
  required bool metaSeen,
  required int? seen,
  required int? incoming,
}) =>
    metaSeen && incoming != null && incoming != seen;
