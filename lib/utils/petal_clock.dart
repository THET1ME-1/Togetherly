/// Ключ секунды для лепесткового круга.
///
/// Круг перерисовывается по развёртке экрана — шестьдесят кадров в секунду, — а
/// цифры на нём меняются раз в секунду по определению: годы, месяцы, дни, часы,
/// минуты и секунды. Считать календарную арифметику на каждом кадре значит
/// шесть раз в кадр создавать одни и те же значения.
///
/// По этому ключу расчёт держится до смены секунды. Плавность не страдает:
/// заливка и вращение живут своей анимацией и к нему не привязаны.
int petalSecondKey(DateTime now) => now.millisecondsSinceEpoch ~/ 1000;
