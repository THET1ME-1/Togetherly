/// День календаря на [days] дальше [day] (назад, если число отрицательное),
/// в полночь.
///
/// Не `day.add(Duration(days: n))`: там, где переводят часы (Украина, Молдова,
/// Европа, Израиль), сутки перевода длятся 23 или 25 часов, и 24-часовой шаг от
/// полуночи уезжает в 23:00 того же дня или в 01:00 следующего. 25.10.2026 так
/// полоса дней на главной показала воскресенье дважды (обращение 433), а «вчера»
/// в чате наутро после перевода не узнавалось.
DateTime calendarDay(DateTime day, int days) =>
    DateTime(day.year, day.month, day.day + days);
