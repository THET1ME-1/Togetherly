/// Локальные файлы картинок-штрихов холста: id штриха → путь на диске.
///
/// Заливка и вставленная картинка сначала живут файлом во временной папке, а
/// потом уезжают на сервер. Серверная запись возвращается под СВОИМ id, и если
/// не перенести путь на него, виджет начинает качать по сети только что
/// отправленный нами же файл: пятно заливки пропадает, на его месте крутится
/// индикатор, затем картинка возвращается. Именно так выглядело моргание при
/// заливке.
library;

/// Переносит путь с локального id на серверный. Возвращает true, если было что
/// переносить — по этому признаку удобно понимать, тронули ли карту.
bool adoptLocalImagePath(
  Map<String, String> paths,
  String localId,
  String remoteId,
) {
  if (localId == remoteId) return false;
  final path = paths[localId];
  if (path == null) return false;
  paths[remoteId] = path;
  paths.remove(localId);
  return true;
}
