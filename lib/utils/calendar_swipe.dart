/// Скорость пальца (точек в секунду), с которой движение считается свайпом.
const double kCalendarSwipeVelocity = 300;

/// Куда листать календарь по горизонтальному свайпу: `1` — следующий период
/// (палец влево), `-1` — прошлый (палец вправо), `0` — не свайп.
///
/// Просьба владельца 08.11.2026: месяцы листать свайпом, а не только
/// стрелками. Медленное движение пальца — не свайп: иначе календарь уезжал бы,
/// когда человек просто ведёт пальцем по сетке.
int calendarSwipeShift(double velocity) {
  if (velocity.abs() < kCalendarSwipeVelocity) return 0;
  return velocity < 0 ? 1 : -1;
}
