import 'plus_access.dart';

/// Что делать по нажатию на карточку «Цикл».
enum CycleTap {
  /// Открыть лист отметок.
  open,

  /// Предложить покупку.
  offer,

  /// Ещё не знаем, куплен ли Togetherly+ — ждём ответа и не трогаем человека.
  wait,

  /// Платформа без Togetherly+: строки цикла тут нет вовсе.
  nothing,
}

/// [known] — прочитан ли флаг `users.plus` этого аккаунта.
///
/// До первого чтения флаг равен false, то есть гейт говорит «не куплено» о
/// человеке, который заплатил. Правило проекта с 19 августа 2026: всё, что
/// ПРЕДЛАГАЕТ покупку, обязано сперва дождаться ответа — иначе купившая
/// попадает на витрину вместо своей функции. На главном экране это уже учтено,
/// а карточка цикла спрашивала гейт сразу и уводила на экран Togetherly+, где
/// написано «Плюс ваш, всё открыто». Так это и выглядело в жалобах: «мы нажали,
/// и нету такого, даже если есть подписка, нету цикла» (01.09.2026).
///
/// Открыть по незнанию нельзя тоже: цикл платный, и бесплатная выдача — не
/// меньшая ошибка. Поэтому третий ответ — [CycleTap.wait]: подождать флаг.
CycleTap cycleTapAction({required PlusGate gate, required bool known}) {
  if (gate == PlusGate.hidden) return CycleTap.nothing;
  if (gate == PlusGate.open) return CycleTap.open;
  return known ? CycleTap.offer : CycleTap.wait;
}
