/// Память о том, где лежит уже найденная запись.
///
/// Записи, которые обновляются постоянно — геопозиция, присутствие, «печатает»,
/// данные виджета, — ищутся фильтром, а не по id. Каждое обновление выливалось в
/// три запроса: поиск (часто 404, потому что правила коллекции своей же записи
/// не показывают), создание (отказ «Value must be unique») и только потом
/// обновление найденной. В журнале сервера это 500 отказов в час, а на
/// медленной связи — лишние секунды там, где человек ждёт.
///
/// Запомнив id один раз, следующее обновление делаем сразу по нему. Промах
/// (запись удалили, сменился аккаунт) сбрасывает память и возвращает прежний
/// путь — так что хуже, чем было, не станет.
class UpsertIdCache {
  final Map<String, String> _ids = {};

  /// Ключ строится из коллекции и фильтра: один и тот же фильтр всегда ведёт к
  /// одной записи.
  static String keyOf(String collection, String filter) => '$collection|$filter';

  String? operator [](String key) => _ids[key];

  void remember(String key, String id) {
    if (key.isEmpty || id.isEmpty) return;
    _ids[key] = id;
  }

  void forget(String key) => _ids.remove(key);

  /// Смена аккаунта: чужие id больше не наши.
  void clear() => _ids.clear();

  int get length => _ids.length;
}
