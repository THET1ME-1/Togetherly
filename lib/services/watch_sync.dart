/// Правила совместного просмотра: кто задаёт время и когда за ним догонять.
///
/// До 1.23.0 отметку времени слали ОБА клиента раз в три секунды, и каждый
/// подстраивался под другого. Пока сообщение шло по сети, отправитель уходил
/// вперёд, приёмник прыгал назад на величину задержки, следом второй прыгал
/// назад к нему — и так по кругу. В отзыве это выглядело как «каждые 5-10
/// секунд перематывает на пару секунд, 2-3 раза».
///
/// Лечится асимметрией: время задаёт ровно один участник, второй молча
/// подстраивается.
library;

/// Оценка дороги сообщения до партнёра.
///
/// Прыгать ровно в присланную секунду нельзя: пока отметка летела, ведущий
/// ушёл дальше, и ведомый оказывается позади — через три секунды прилетит
/// новая отметка и всё повторится. Полсекунды примерно покрывают путь через
/// Centrifugo и разбор сообщения.
const Duration kSyncLag = Duration(milliseconds: 500);

/// Кто задаёт время в комнате.
///
/// Решение обязано совпасть у обоих без переговоров, поэтому берётся
/// сравнение идентификаторов, а не «кто первым вошёл»: порядок входа каждый
/// видит по-своему, а идентификаторы у пары одни и те же.
bool leadsSync({required String me, required String peer}) {
  if (peer.isEmpty) return true;
  return me.compareTo(peer) <= 0;
}

/// Куда перемотать, получив отметку ведущего. Null — оставить как есть.
///
/// [drift] — допуск, внутри которого расхождение не стоит рывка: реплики в
/// фильме при полутора секундах ещё звучат вместе, а прыжок виден всегда.
Duration? catchUpTarget({
  required Duration mine,
  required Duration theirs,
  required bool playing,
  required Duration drift,
}) {
  if ((mine - theirs).abs() <= drift) return null;
  final target = playing ? theirs + kSyncLag : theirs;
  return target < Duration.zero ? Duration.zero : target;
}
