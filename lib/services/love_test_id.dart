import 'dart:convert';

import 'package:crypto/crypto.dart';

/// Id записи «Умения любить»: 15 символов под маску коллекции `^[a-z0-9]+$`.
///
/// Собирался из хвостов пары и человека — и ломался на аккаунтах, приехавших
/// из Firebase: там смешанный регистр и дефисы, а PocketBase отвечает на такой
/// id `400 {"id":"Invalid value format."}`. Результат теста не сохранялся
/// вовсе, и после перезапуска приложение просило пройти его заново (жалоба
/// 18.08.2026: на проде ноль записей при живом отказе в журнале).
///
/// Хеш решает обе задачи разом: любые входные символы дают строчный hex, а
/// пара «группа + человек» остаётся одной записью, как и было задумано —
/// повторное прохождение правит её, а не плодит вторую. Тем же приёмом живёт
/// `iap_purchases.id` (там sha256 от токена покупки).
String loveTestRecordId(String groupId, String uid) {
  final digest = sha256.convert(utf8.encode('$groupId:$uid')).toString();
  return 'lt${digest.substring(0, 13)}';
}
