/// Режим смены снимков в фото-виджете.
///
/// Пока снимок один, крутить нечего, и в настройки виджета пишется `none` —
/// нативная сторона по нему понимает, что вращать не нужно. Но человек, добавив
/// второй снимок, открывает настройку и видит два НЕзакрашенных кружка: ни
/// «При разблокировке», ни «По времени». Выглядит как «ничего не выбрано»,
/// хотя карусель уже включена и по умолчанию меняет фото при разблокировке.
///
/// Поэтому редактор показывает не сырое значение, а приведённое: всё, что не
/// «time», читается как «unlock» — ровно так же, как это понимает Android
/// (`PhotoDayRotationReceiver` берёт «unlock» значением по умолчанию).
String rotationTypeForEditor(String? stored) =>
    stored == 'time' ? 'time' : 'unlock';
