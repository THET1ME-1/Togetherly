def день(строка: str) -> date:
    return date.fromisoformat(строка)


def разложить(начало: str, правило: str, выброшены: list, с: str, по: str) -> list:
    """Дни повтора в окне [с, по] включительно, как их видит dateutil."""
    старт = день(начало)
    if not правило:
        дни = [старт] if день(с) <= старт <= день(по) else []
    else:
        r = rrulestr(правило, dtstart=datetime.combine(старт, time()))
        дни = [d.date() for d in r.between(datetime.combine(день(с), time()),
                                           datetime.combine(день(по), time()), inc=True)]
    return [d.isoformat() for d in дни if d.isoformat() not in выброшены]


