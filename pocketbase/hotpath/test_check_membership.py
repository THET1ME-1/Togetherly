#!/usr/bin/env python3
"""Ночная сверка членства не держит запись PocketBase (19.10.2026).

`check_membership.py --fix` каждую ночь в 03:41 запирал запись PocketBase на
5–6 минут: 3125 человек «помнили лишнюю пару», и каждого он правил отдельным
UPDATE с перебором всех групп, одной транзакцией. Лишней пара была только на
взгляд проверки: человек состоит в распущенной паре, а такую пару приложение
держит в списке намеренно (её можно поднять со всей историей). Правка
возвращала тот же список, и назавтра всё повторялось. К базе в это время
стояло до 272 запросов.

Теперь целевой список считается в Python по всем парам, где человек в
составе, правятся только те, у кого он правда расходится, а запись идёт
пачками с отдельными транзакциями.

    python3 test_check_membership.py
"""

import sqlite3

from check_membership import применить, разобрать

провалы = []


def проверить(имя, ok, подробно=""):
    print(("ОК   " if ok else "ПЛОХО") + f" {имя} {'' if ok else подробно}")
    if not ok:
        провалы.append(имя)


группы = [
    ("живая", ["аня", "боря"], False),
    ("распущенная", ["аня", "вика"], True),
    ("ушёл", ["гена"], False),
    ("новая", ["дима", "ева"], False),
]
есть = {
    "аня": {"живая", "распущенная"},     # всё верно: распущенную пару помнит намеренно
    "боря": {"живая", "ушёл"},          # из «ушёл» его убрали из состава
    "вика": {"распущенная"},
    "гена": {"ушёл"},
    "дима": set(),                     # не видит свою пару: запись закрыта
}
нет_пары, правки = разобрать(группы, есть)
по_людям = dict(правки)

проверить("распущенная пара, где человек в составе, не правится",
          "аня" not in по_людям and "вика" not in по_людям, str(правки))
проверить("пара, откуда человека убрали, снимается",
          по_людям.get("боря") == ["живая"], str(по_людям.get("боря")))
проверить("недостающая живая пара добавляется", по_людям.get("дима") == ["новая"],
          str(по_людям.get("дима")))
проверить("кто не видит свою пару, тот в отчёте", нет_пары == [("дима", ["новая"])],
          str(нет_пары))
проверить("человека без учётки не трогаем", "ева" not in по_людям)

db = sqlite3.connect(":memory:")
db.execute("CREATE TABLE users (id TEXT PRIMARY KEY, group_ids TEXT)")
db.executemany("INSERT INTO users VALUES (?, ?)",
               [(f"u{i}", '["старая"]') for i in range(5)])
пачек = применить(db, [(f"u{i}", ["новая", f"п{i}"]) for i in range(5)], пачка=2, пауза=0)
строки = dict(db.execute("SELECT id, group_ids FROM users"))
проверить("список пишется в виде PocketBase", строки["u3"] == '["новая","п3"]', строки["u3"])
проверить("пять правок легли тремя пачками", пачек == 3, str(пачек))
проверить("после записи транзакция закрыта", not db.in_transaction)

print(f"\nпровалов: {len(провалы)}")
raise SystemExit(1 if провалы else 0)
