# -*- coding: utf-8 -*-
"""Зеркало присутствия при спешащих часах: python3 pocketbase/hotpath/test_presence_mirror.py

hotpath раз в пять минут переносит свежие отметки присутствия из Postgres в
SQLite PocketBase. Свежесть он мерил меткой — самой поздней отметкой
прошлого переноса. Один телефон со спешащими часами прислал отметку на
28.10.2026, метка уехала туда же, и 21.10.2026 в SQLite за час попадали две
отметки вместо пяти тысяч: когорты, «был в сети» админки и утренний пуш
сундука смотрели на застывшие данные.
"""
import os

путь = os.path.join(os.path.dirname(__file__), "hotpath.py")
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(путь, encoding="utf-8").read()
начало = источник.index("def _метка_зеркала")
конец = источник.index("async def _presence_mirror_worker")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
метка = пространство["_метка_зеркала"]

сейчас = 1_792_600_000_000.0  # 21.10.2026, мс
НЕДЕЛЯ = 7 * 24 * 3600_000
ok = True


def проверка(имя: str, условие: bool) -> None:
    global ok
    ok = ok and условие
    print(("  ✓ " if условие else "  ✗ ") + имя)


проверка("обычные отметки двигают метку к самой поздней",
         метка([сейчас - 60_000, сейчас - 5_000], сейчас) == сейчас - 5_000)
проверка("отметка из будущего не уводит метку дальше «сейчас»",
         метка([сейчас - 60_000, сейчас + НЕДЕЛЯ], сейчас) == сейчас)
# Метка дальше «сейчас» — значит, следующий перенос возьмёт свежие отметки.
следующая = метка([сейчас + НЕДЕЛЯ], сейчас)
проверка("свежая отметка через пять минут попадёт в следующий перенос",
         сейчас + 300_000 > следующая)

print("\nвсё прошло" if ok else "\nЕСТЬ ПАДЕНИЯ")
raise SystemExit(0 if ok else 1)
