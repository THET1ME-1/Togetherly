# -*- coding: utf-8 -*-
"""Даты воспоминания при сбитых часах: python3 pocketbase/hotpath/test_memory_dates.py

Дату записи ставит телефон автора. 14.10.2026 у пары в ленте висели сверху
11 «фото дня» с датами 19–31 октября: сервер получил их 12-го, а часы
телефона ушли вперёд. Лента сортирует по дате, и всё новое пряталось под ними
до 1 ноября.
"""
import importlib.util
import os
import sys

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("РАСХОЖДЕНИЕ_ЧАСОВ_MS")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
даты_воспоминания = пространство["даты_воспоминания"]

# 12.10.2026 17:33:26 UTC — момент, когда сервер принял первое «фото дня».
сервер_мс = 1_791_826_406_000
ЧАС = 3_600_000
СУТКИ = 24 * ЧАС
ok = True


def iso(мс: int) -> str:
    """Как пишет телефон: PairTime.write → toUtc().toIso8601String()."""
    from datetime import datetime, timezone
    t = datetime.fromtimestamp(мс / 1000, tz=timezone.utc)
    return t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{t.microsecond:06d}Z"


def мс(значение) -> int:
    from datetime import datetime
    return int(datetime.fromisoformat(
        str(значение).replace(" ", "T").replace("Z", "+00:00")).timestamp() * 1000)


def тело(создано: int, занесено: int | None):
    t = {"created_at": iso(создано), "data": {"createdAt": iso(создано)}}
    if занесено is not None:
        t["added_at"] = iso(занесено)
        t["data"]["addedAt"] = iso(занесено)
    return t


def check(имя, условие):
    global ok
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ok = False


print("даты воспоминания")

t = даты_воспоминания(тело(сервер_мс + 7 * СУТКИ, сервер_мс + 7 * СУТКИ), сервер_мс)
check("часы спешат на неделю — запись встаёт на сегодня",
      abs(мс(t["created_at"]) - сервер_мс) < 1000
      and abs(мс(t["added_at"]) - сервер_мс) < 1000)
check("в data те же даты, что в колонках",
      t["data"]["createdAt"] == t["created_at"]
      and t["data"]["addedAt"] == t["added_at"])

t = даты_воспоминания(
    тело(сервер_мс + 5 * СУТКИ, сервер_мс + 7 * СУТКИ), сервер_мс)
check("дата «два дня назад» по сбитым часам — два дня назад по настоящим",
      abs(мс(t["created_at"]) - (сервер_мс - 2 * СУТКИ)) < 1000)

t = даты_воспоминания(тело(сервер_мс + 3 * СУТКИ, сервер_мс), сервер_мс)
check("часы верные, дату выбрали в будущем — сегодня",
      abs(мс(t["created_at"]) - сервер_мс) < 1000)

t = даты_воспоминания(тело(сервер_мс - 5 * ЧАС, сервер_мс - 5 * ЧАС), сервер_мс)
check("записали без сети пять часов назад — время остаётся",
      мс(t["created_at"]) == сервер_мс - 5 * ЧАС
      and мс(t["added_at"]) == сервер_мс - 5 * ЧАС)

t = даты_воспоминания(тело(сервер_мс - 3 * 365 * СУТКИ, сервер_мс), сервер_мс)
check("старое воспоминание задним числом не трогаем",
      мс(t["created_at"]) == сервер_мс - 3 * 365 * СУТКИ)

t = даты_воспоминания(тело(сервер_мс + 60_000, сервер_мс + 60_000), сервер_мс)
check("часы спешат на минуту — в пределах допуска, не трогаем",
      мс(t["created_at"]) == сервер_мс + 60_000)

t = даты_воспоминания(тело(сервер_мс + 2 * СУТКИ, None), сервер_мс)
check("старая сборка без added_at — будущая дата всё равно сегодня",
      abs(мс(t["created_at"]) - сервер_мс) < 1000 and "added_at" not in t)

t = даты_воспоминания({"created_at": "вчера", "data": {"createdAt": None}},
                      сервер_мс)
check("мусор вместо даты не роняет разбор", t["created_at"] == "вчера")

t = даты_воспоминания({"caption": "только подпись"}, сервер_мс)
check("правка без дат проходит как есть", t == {"caption": "только подпись"})

print("всё сошлось" if ok else "ЕСТЬ ОШИБКИ")
sys.exit(0 if ok else 1)
