# -*- coding: utf-8 -*-
"""Приём кода и своё пространство: python3 pocketbase/hotpath/test_pair_accept_solo.py

Обращение 597, 07.11.2026: «заполнила все воспоминания, все таймеры выставила…
а после подключения к партнёру всё обнулилось». До пары человек живёт в своей
группе из одного участника. Приём кода не смотрел на группу принимающего: шёл
в живую пару приглашающего, а нет её — заводил новую, пустую. Прежняя группа
оставалась живой и невидимой; на 07.11.2026 так брошены данные у 85 человек
(153 воспоминания, 1816 линий рисунков).

Правило `порядок_основы`: на чьей группе строится пара. Своя группа
принимающего идёт первой, если в ней больше, чем в группе приглашающего, и
вместо новой пары, если у приглашающего места нет.
"""
import os

источник = open(os.path.join(os.path.dirname(__file__), "hotpath.py"), encoding="utf-8").read()
начало = источник.index("def порядок_основы")
конец = источник.index("\n\n\n", начало)
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
порядок_основы = пространство["порядок_основы"]

ok = True


def check(имя, условие):
    global ok
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ok = False


print("на чьей группе строится пара")
check("своей группы нет — как раньше, к приглашающему",
      порядок_основы(у_хозяина=0, у_меня=None) == ["хозяин"])
check("ни у кого ничего — к приглашающему, новая пара только если и там некуда",
      порядок_основы(у_хозяина=None, у_меня=None) == [])
check("у приглашающего места нет — своя группа вместо новой пустой (обращение 597)",
      порядок_основы(у_хозяина=None, у_меня=9) == ["мой"])
# Пустая своя не опережает подъём общей распущенной пары с историей: она
# встаёт только на место новой пустой группы, это делает сам приём кода.
check("у приглашающего места нет, своя пустая — не раньше общей распущенной",
      порядок_основы(у_хозяина=None, у_меня=0) == [])
check("своя пустая занимает место новой пары", "вместо новой — своя пустая" in источник)
check("у меня воспоминания, у приглашающего пусто — моя первой",
      порядок_основы(у_хозяина=0, у_меня=3) == ["мой", "хозяин"])
check("у приглашающего больше — его первой, моя запасной",
      порядок_основы(у_хозяина=5, у_меня=2) == ["хозяин", "мой"])
check("поровну — как раньше, приглашающего первой",
      порядок_основы(у_хозяина=2, у_меня=2) == ["хозяин", "мой"])

check("приглашающий, вошедший в чужую группу, получает событие создания",
      "событие=\"create\" if новая else \"update\"" in источник and "\"_new\": кто == хозяин" in источник)

raise SystemExit(0 if ok else 1)
