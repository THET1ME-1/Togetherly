#!/usr/bin/env python3
"""Часы в приложении для званий: сервер засчитывает не больше реального времени.

Телефон считает секунды, пока приложение на экране, и шлёт их пачкой
(`POST /api/user/app-time`). Правило `_app_time_grant` решает, сколько из
присланного засчитать: не больше, чем прошло с прошлого отчёта этого телефона
(плюс 30 секунд на сеть), не больше часа за раз; первый отчёт телефона — не
больше пяти минут. Так переведённые часы на телефоне и подделанный запрос не
дают «Легенду» за вечер (план 2026-11-05-ranks-by-hours, задача 2).

Запуск: python3 pocketbase/hotpath/test_app_time.py
"""
import unittest
from pathlib import Path

источник = (Path(__file__).parent / "hotpath.py").read_text(encoding="utf-8")
начало = источник.index("_APP_TIME_CALL_MAX")
конец = источник.index("\n\n\n", источник.index("def _app_time_grant("))
среда: dict = {}
exec(источник[начало:конец], среда)
засчитать = среда["_app_time_grant"]

СЕЙЧАС = 1_800_000_000_000
МИНУТА = 60_000


class ЧасыВПриложении(unittest.TestCase):
    def test_обычный_отчёт_засчитывается_целиком(self):
        self.assertEqual(засчитать(300, СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 300)

    def test_больше_прошедшего_времени_не_засчитывается(self):
        # Прошло 5 минут, прислали час: засчитываем 5 минут и 30 секунд на сеть.
        self.assertEqual(засчитать(3600, СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 330)

    def test_не_больше_часа_за_раз(self):
        self.assertEqual(засчитать(10_000, СЕЙЧАС - 300 * МИНУТА, СЕЙЧАС), 3600)

    def test_первый_отчёт_телефона_не_больше_пяти_минут(self):
        self.assertEqual(засчитать(1200, None, СЕЙЧАС), 300)
        self.assertEqual(засчитать(120, None, СЕЙЧАС), 120)

    def test_мусор_и_отрицательное_не_засчитываются(self):
        for плохое in (-5, 0, "много", None, 1.5e12):
            with self.subTest(плохое=плохое):
                self.assertLessEqual(засчитать(плохое, СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 330)
                self.assertGreaterEqual(засчитать(плохое, СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 0)
        self.assertEqual(засчитать("много", СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 0)
        self.assertEqual(засчитать(-5, СЕЙЧАС - 5 * МИНУТА, СЕЙЧАС), 0)

    def test_часы_сервера_назад_не_дают_отрицательного(self):
        self.assertEqual(засчитать(100, СЕЙЧАС + 10 * МИНУТА, СЕЙЧАС), 0)


if __name__ == "__main__":
    unittest.main()
