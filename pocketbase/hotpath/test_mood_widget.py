# -*- coding: utf-8 -*-
"""Настроение в виджет пары: python3 pocketbase/hotpath/test_mood_widget.py

Виджет пары на рабочем столе читает `widget_data` автора, а не календарь.
Обращение 265 (14.10.2026): «на виджете у партнёра „Радость“, хотя у него
стоит „Люблю“, так уже два дня». Отметка настроения доходила (очередь), а
запись виджета — нет: приложение пишет её отдельным прямым запросом без
повтора, а отметка кнопкой с виджета настроений её не трогает вовсе.
Теперь свежую отметку в виджет переносит сервер. Здесь — какая отметка
считается свежей.
"""
import importlib.util
import os

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("РАСХОЖДЕНИЕ_ЧАСОВ_MS")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
момент = пространство["момент_свежего_настроения"]

СЕЙЧАС = 1_791_826_406_000          # 12.10.2026 17:33:26 UTC
МИН = 60_000
ЧАС = 60 * МИН
ok = True


def iso(мс: int) -> str:
    """Как пишет телефон: PairTime.write → toUtc().toIso8601String()."""
    from datetime import datetime, timezone
    t = datetime.fromtimestamp(мс / 1000, tz=timezone.utc)
    return t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{t.microsecond:06d}Z"


def отметка(мс: int, **поля) -> dict:
    o = {"group_id": "g1", "user_uid": "u1", "label": "Люблю",
         "image_path": "assets/images/mood_packs/bunny/love.webp",
         "timestamp": iso(мс)}
    o.update(поля)
    return o


def проверить(имя: str, условие: bool) -> None:
    global ok
    print(("✓ " if условие else "✗ ") + имя)
    ok = ok and условие


проверить("отметка «сейчас» идёт в виджет",
          момент(отметка(СЕЙЧАС - МИН), СЕЙЧАС) == СЕЙЧАС - МИН)
проверить("запоздавшая из очереди (пять часов) идёт в виджет",
          момент(отметка(СЕЙЧАС - 5 * ЧАС), СЕЙЧАС) == СЕЙЧАС - 5 * ЧАС)
проверить("отметка задним числом за вчера виджет не трогает",
          момент(отметка(СЕЙЧАС - 24 * ЧАС), СЕЙЧАС) is None)
проверить("старше шести часов — не трогает",
          момент(отметка(СЕЙЧАС - 7 * ЧАС), СЕЙЧАС) is None)
проверить("часы телефона спешат на пять минут — идёт",
          момент(отметка(СЕЙЧАС + 5 * МИН), СЕЙЧАС) == СЕЙЧАС + 5 * МИН)
проверить("отметка из будущего дальше десяти минут — нет",
          момент(отметка(СЕЙЧАС + 30 * МИН), СЕЙЧАС) is None)
проверить("время в виде базы (пробел, миллисекунды, Z) читается",
          момент(отметка(0, timestamp="2026-10-12 17:30:26.000Z"), СЕЙЧАС)
          == СЕЙЧАС - 3 * МИН)
проверить("мусор вместо времени — нет",
          момент(отметка(0, timestamp="вчера"), СЕЙЧАС) is None)
проверить("без пары — нет", момент(отметка(СЕЙЧАС, group_id=""), СЕЙЧАС) is None)
проверить("без автора — нет", момент(отметка(СЕЙЧАС, user_uid=""), СЕЙЧАС) is None)
проверить("ни картинки, ни подписи — нет",
          момент(отметка(СЕЙЧАС, image_path="", label=""), СЕЙЧАС) is None)

print("ВСЁ ВЕРНО" if ok else "ЕСТЬ ОШИБКИ")
raise SystemExit(0 if ok else 1)
