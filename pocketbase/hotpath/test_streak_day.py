#!/usr/bin/env python3
"""Общий день пары засчитывается и тогда, когда партнёры в разных поясах.

Отзыв 16.08.2026: «серийчик не всегда хорошо работает». Замер по живой базе:
у 18 143 пар из 31 780 серия равна единице, дольше недели держится у 252 пар
(0,8%), а 16 029 пар прямо сейчас висят в состоянии «один зашёл, второго
ждём».

Одна из причин видна в цифрах: **22% активных пар живут в разных часовых
поясах** (1799 из 8162 — считано по колонке `tz` у отметок настроения). Дату
«сегодня» присылает клиент по своим часам, а условие требовало ПОЛНОГО
совпадения строк. У пары из Москвы и Владивостока даты расходятся каждый
вечер, и общий день не засчитывался никогда: второй заход просто перезаписывал
ожидание своей датой.

Правило теперь мягче ровно на разницу поясов: соседний день тоже считается
общим. Дальше суток — нет, иначе серия перестанет означать «мы оба тут».

Запуск: python3 pocketbase/hotpath/test_streak_day.py
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
# Модуль поднимает подключения при импорте, поэтому берём только нужные функции.
import importlib.util

spec = importlib.util.spec_from_file_location(
    "hotpath_src", Path(__file__).parent / "hotpath.py")
источник = spec.loader.get_source("hotpath_src")

# Вырезаем интересующие нас функции без запуска модуля целиком.
import time

пространство: dict = {"time": time}
начало = источник.index("def _общий_день(")
конец = источник.index("\ndef ", начало + 10)
exec(compile(источник[начало:конец], "hotpath.py", "exec"), пространство)
_общий_день = пространство["_общий_день"]


class ОбщийДень(unittest.TestCase):
    def test_один_пояс_даты_совпадают(self):
        self.assertTrue(_общий_день("2026-08-16", "2026-08-16"))

    def test_разные_пояса_даты_соседние(self):
        # Она во Владивостоке уже 17-го, он в Москве ещё 16-го.
        self.assertTrue(_общий_день("2026-08-17", "2026-08-16"))
        self.assertTrue(_общий_день("2026-08-16", "2026-08-17"))

    def test_через_месяц_тоже_соседние(self):
        self.assertTrue(_общий_день("2026-09-01", "2026-08-31"))

    def test_разрыв_в_двое_суток_не_считается(self):
        self.assertFalse(_общий_день("2026-08-18", "2026-08-16"))

    def test_пустая_дата_не_считается(self):
        self.assertFalse(_общий_день("2026-08-16", ""))
        self.assertFalse(_общий_день("", "2026-08-16"))

    def test_мусор_не_роняет(self):
        self.assertFalse(_общий_день("2026-08-16", "позавчера"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
