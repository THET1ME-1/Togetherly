# -*- coding: utf-8 -*-
"""Отметка времени сообщения чата: python3 pocketbase/hotpath/test_chat_ts.py

Порядок в чате держится на `ts`, и ставит его телефон отправителя. Жалоба
17.08.2026: «почему-то ответ оказывается выше сообщения, на которое даётся
ответ» — ровно то, что выходит при сбитых часах.
"""
import importlib.util
import os
import sys

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("РАСХОЖДЕНИЕ_ЧАСОВ_MS")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
время_сообщения = пространство["время_сообщения"]

сервер = 1_755_000_000_000
ok = True


def check(имя, условие):
    global ok
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ok = False


print("отметка времени сообщения")
check("ровные часы — своё время остаётся",
      время_сообщения(сервер - 5_000, сервер) == сервер - 5_000)
check("минута назад — тоже своё (сообщение из офлайна)",
      время_сообщения(сервер - 60_000, сервер) == сервер - 60_000)
check("часы отстали на час — берём серверное",
      время_сообщения(сервер - 3_600_000, сервер) == сервер)
check("часы спешат на сутки — берём серверное",
      время_сообщения(сервер + 86_400_000, сервер) == сервер)
check("нет отметки — серверное", время_сообщения(None, сервер) == сервер)
check("мусор вместо числа — серверное", время_сообщения("вчера", сервер) == сервер)
check("ноль — серверное", время_сообщения(0, сервер) == сервер)
check("дробное клиентское число не роняет разбор",
      время_сообщения(float(сервер - 1000), сервер) == сервер - 1000)

print("всё сошлось" if ok else "ЕСТЬ ОШИБКИ")
sys.exit(0 if ok else 1)
