# -*- coding: utf-8 -*-
"""Отметка времени сообщения чата: python3 pocketbase/hotpath/test_chat_ts.py

Порядок в чате держится на `ts`, и ставит его телефон отправителя. Жалоба
17.08.2026: «почему-то ответ оказывается выше сообщения, на которое даётся
ответ» — ровно то, что выходит при сбитых часах.
"""
import importlib.util
import os
import sys

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("РАСХОЖДЕНИЕ_ЧАСОВ_MS")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
время_сообщения = пространство["время_сообщения"]

сервер = 1_755_000_000_000
ok = True


def check(имя, условие):
    global ok
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ok = False


print("отметка времени сообщения")
check("ровные часы — своё время остаётся",
      время_сообщения(сервер - 5_000, сервер) == сервер - 5_000)
check("минута назад — тоже своё (сообщение из офлайна)",
      время_сообщения(сервер - 60_000, сервер) == сервер - 60_000)
check("часы отстали на час — берём серверное",
      время_сообщения(сервер - 3_600_000, сервер) == сервер)
check("часы спешат на сутки — берём серверное",
      время_сообщения(сервер + 86_400_000, сервер) == сервер)
check("нет отметки — серверное", время_сообщения(None, сервер) == сервер)
check("мусор вместо числа — серверное", время_сообщения("вчера", сервер) == сервер)
check("ноль — серверное", время_сообщения(0, сервер) == сервер)
check("дробное клиентское число не роняет разбор",
      время_сообщения(float(сервер - 1000), сервер) == сервер - 1000)

# Обращение 409, 21.10.2026: «окей», написанное без сети в 11:27, очередь
# довезла в 13:12, и сервер поставил ему 13:12 — оно встало ответом на
# другое сообщение, «бот сам за меня отвечает». По одному `ts` сбитые часы от
# поздней доставки не отличить, поэтому новые сборки присылают и свои часы в
# момент отправки: разница с серверными и есть сдвиг часов телефона.
ЧАС = 3_600_000
print("часы телефона в момент отправки")
check("сеть пропала на два часа — сообщение встаёт на время написания",
      время_сообщения(сервер - 2 * ЧАС, сервер, сервер) == сервер - 2 * ЧАС)
check("часы отстали на час, сообщение свежее — время написания по серверу",
      время_сообщения(сервер - ЧАС - 5_000, сервер, сервер - ЧАС) == сервер - 5_000)
check("часы отстали на час и сети не было два часа",
      время_сообщения(сервер - 3 * ЧАС, сервер, сервер - ЧАС) == сервер - 2 * ЧАС)
check("часы спешат на сутки — тоже время написания",
      время_сообщения(сервер + 24 * ЧАС - 5_000, сервер, сервер + 24 * ЧАС) == сервер - 5_000)
check("написано «позже» отправки — не в будущее",
      время_сообщения(сервер + ЧАС, сервер, сервер) == сервер)
check("старше недели — серверное, это мусор, а не офлайн",
      время_сообщения(сервер - 8 * 24 * ЧАС, сервер, сервер) == сервер)
check("мусор вместо часов отправки — прежнее правило",
      время_сообщения(сервер - 3 * ЧАС, сервер, "вчера") == сервер)
check("без часов отправки (старые сборки) — прежнее правило",
      время_сообщения(сервер - 3 * ЧАС, сервер) == сервер)

print("всё сошлось" if ok else "ЕСТЬ ОШИБКИ")
sys.exit(0 if ok else 1)
