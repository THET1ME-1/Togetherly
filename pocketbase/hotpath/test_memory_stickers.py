# -*- coding: utf-8 -*-
"""Наклейки на пинах: python3 pocketbase/hotpath/test_memory_stickers.py

Наклейку на запись ставит любой из пары, пишет её сервер отдельной операцией
(`sticker_put` / `sticker_del` в PATCH воспоминания). Здесь проверяется правило:
кто что может, предел три своих на запись, разбор присланного. Те же правила
у клиента — `lib/models/memory_sticker.dart`.
"""
import importlib.util
import math
import os

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
# Модуль поднимает соединения при импорте, поэтому берём из файла только правило.
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("НАКЛЕЕК_НА_ЧЕЛОВЕКА =")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
наклейка_из_тела = пространство["наклейка_из_тела"]
применить_наклейку = пространство["применить_наклейку"]

СЕЙЧАС = 1_791_826_406_000
КАРТИНКА = "assets/images/mood_packs/bunny/love.webp"
ok = True


def проверить(имя: str, условие: bool) -> None:
    global ok
    print(("✓ " if условие else "✗ ") + имя)
    ok = ok and условие


def наклейка(sid: str, **поля) -> dict:
    тело = {"id": sid, "uid": "кто-то", "img": КАРТИНКА, "pack": "bunny",
            "mood": "love", "x": .5, "y": .5, "s": .28, "r": 0.0, "t": 1}
    тело.update(поля)
    return тело


# ── разбор присланного ─────────────────────────────────────────────────────
s = наклейка_из_тела(наклейка("a1", uid="чужой", x=3, y=-1, s=9, r=7), "я", СЕЙЧАС)
проверить("автором наклейки сервер ставит того, кто прислал", s["uid"] == "я")
проверить("центр прижат к блоку", s["x"] == 1.0 and s["y"] == 0.0)
проверить("размер прижат к пределу", s["s"] == 0.7)
проверить("поворот сведён к ±π", abs(s["r"] - (7 - 2 * math.pi)) < 1e-9)
проверить("чужой адрес картинки не берётся",
          наклейка_из_тела(наклейка("a2", img="https://evil.example/x.webp"),
                           "я", СЕЙЧАС) is None)
проверить("выход из папки не берётся",
          наклейка_из_тела(наклейка("a3", img="assets/../x"), "я", СЕЙЧАС) is None)
проверить("картинка каталога берётся",
          наклейка_из_тела(наклейка(
              "a4", img="https://togetherly.day/api/files/catalog_items/dog/love_l1f07p337t.webp"),
              "я", СЕЙЧАС) is not None)
проверить("своё настроение пары берётся",
          наклейка_из_тела(наклейка(
              "a6", img="https://togetherly.day/api/files/custom_moods/k3m9x2p7q1w5e8r/custom_ab12cd34_x9y8z7w6v5.png"),
              "я", СЕЙЧАС) is not None)
проверить("файл другой коллекции не берётся",
          наклейка_из_тела(наклейка(
              "a7", img="https://togetherly.day/api/files/memories/k3m9x2p7q1w5e8r/a.jpg"),
              "я", СЕЙЧАС) is None)
проверить("без id не берётся",
          наклейка_из_тела(наклейка(""), "я", СЕЙЧАС) is None)
проверить("не карта — не берётся", наклейка_из_тела("x", "я", СЕЙЧАС) is None)
проверить("время из будущего становится сейчас",
          наклейка_из_тела(наклейка("a5", t=СЕЙЧАС + 10 ** 9), "я", СЕЙЧАС)["t"] == СЕЙЧАС)

# ── своя наклейка ──────────────────────────────────────────────────────────
пусто: dict = {}
новые, ошибка = применить_наклейку(пусто, {"sticker_put": наклейка("m1")},
                                   "я", "партнёр", СЕЙЧАС)
проверить("наклейка на чужой пин ложится", ошибка is None and "m1" in новые)
проверить("исходная карта не тронута", пусто == {})

три = {f"m{i}": наклейка_из_тела(наклейка(f"m{i}", t=i), "я", СЕЙЧАС)
       for i in range(3)}
_, ошибка = применить_наклейку(три, {"sticker_put": наклейка("m9")},
                               "я", "я", СЕЙЧАС)
проверить("четвёртая своя — отказ", ошибка == "limit")
новые, ошибка = применить_наклейку(три, {"sticker_put": наклейка("p1")},
                                   "партнёр", "я", СЕЙЧАС)
проверить("у партнёра свои три", ошибка is None and len(новые) == 4)

новые, ошибка = применить_наклейку(
    три, {"sticker_put": наклейка("m1", x=.1, y=.9, t=999)}, "я", "я", СЕЙЧАС)
проверить("переставить свою можно и при полном пределе",
          ошибка is None and новые["m1"]["x"] == .1 and новые["m1"]["y"] == .9)
проверить("при перестановке время прежнее (слой не прыгает наверх)",
          новые["m1"]["t"] == три["m1"]["t"])

_, ошибка = применить_наклейку(три, {"sticker_put": наклейка("m1", x=.2)},
                               "партнёр", "партнёр", СЕЙЧАС)
проверить("чужую переставить нельзя", ошибка == "not_yours")

_, ошибка = применить_наклейку(три, {"sticker_put": наклейка("x", img="")},
                               "я", "я", СЕЙЧАС)
проверить("битая наклейка — отказ", ошибка == "bad_sticker")

# ── убрать ─────────────────────────────────────────────────────────────────
новые, ошибка = применить_наклейку(три, {"sticker_del": "m0"}, "я", "партнёр",
                                   СЕЙЧАС)
проверить("свою убрать можно", ошибка is None and "m0" not in новые)
новые, ошибка = применить_наклейку(три, {"sticker_del": "m0"}, "партнёр",
                                   "партнёр", СЕЙЧАС)
проверить("автор пина убирает чужую", ошибка is None and "m0" not in новые)
_, ошибка = применить_наклейку(три, {"sticker_del": "m0"}, "партнёр", "я",
                               СЕЙЧАС)
проверить("чужую на чужом пине убрать нельзя", ошибка == "not_yours")
новые, ошибка = применить_наклейку(три, {"sticker_del": "нет"}, "я", "я",
                                   СЕЙЧАС)
проверить("убрать несуществующую — молча, повтор из очереди безопасен",
          ошибка is None and новые == три)
_, ошибка = применить_наклейку(три, {}, "я", "я", СЕЙЧАС)
проверить("без операции — отказ", ошибка == "bad_sticker")

# ── что лежит в базе ───────────────────────────────────────────────────────
проверить("в карте лежат только известные поля",
          set(новые["m1"]) == {"id", "uid", "img", "pack", "mood", "x", "y",
                               "s", "r", "t"})

print("ВСЁ ВЕРНО" if ok else "ЕСТЬ ОШИБКИ")
raise SystemExit(0 if ok else 1)
