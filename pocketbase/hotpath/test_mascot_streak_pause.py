#!/usr/bin/env python3
"""Смена маскота ставит его серию на паузу, а не обрывает её.

Жалоба из канала 07.11.2026: «у нас пропала серия, хотя мы заходили каждый
день, с 64 на 2 сменилась», потом «почему нигде не было указано, что если
меняешь маскота, то у каждого своя серия». Серия маскота росла, только если
его прошлый засчитанный день был вчера. Пара брала другого маскота на пару
дней, возвращала прежнего, и его серия начиналась с единицы, хотя пара не
пропустила ни дня.

Правило владельца: на Ту 20 дней, сменили на другого — у него 1, потом 5,
вернули Ту — снова 20 и дальше 21. Серия маскота на паузе, пока пара не
пропускает дни: его последний день лежит внутри непрерывной серии пары.
Пропустила пара день — серия рвётся у всех, как и раньше.

Тест гоняет настоящий `_record_activity_pg` на поддельном соединении Postgres.

Запуск: python3 pocketbase/hotpath/test_mascot_streak_pause.py
"""
import json
import unittest

from test_streak_stale_pending import A, B, собрать


def пара(серия, последний, маскот, карта):
    return {
        "members": json.dumps([A, B]), "streak_days": float(серия),
        "streak_last_opened_date": последний, "streak_pending_date": "",
        "streak_pending_uid": "", "active_mascot_id": маскот,
        "mascot_streaks": json.dumps(карта),
    }


def дни(с, по):
    """Дни ноября с `с` по `по` включительно."""
    return [f"2026-11-{d:02d}" for d in range(с, по + 1)]


class Прогон:
    def __init__(self, строка):
        self.отметка, self.conn = собрать(строка)

    def маскот(self, mid):
        self.conn.строка["active_mascot_id"] = mid

    def вместе(self, *дни_):
        import asyncio
        for день in дни_:
            asyncio.run(self.отметка("g", A, A, день))
            asyncio.run(self.отметка("g", B, B, день))

    def карта(self):
        k = self.conn.строка["mascot_streaks"]
        return json.loads(k) if isinstance(k, str) else k

    def серия(self, mid):
        return self.карта().get(mid, {}).get("s", 0)

    @property
    def пары(self):
        return int(self.conn.строка["streak_days"])


class ПаузаПриСмене(unittest.TestCase):
    def test_пример_владельца(self):
        # На Ту 20 дней (последний 01.11), потом 5 дней с Куку, вернули Ту.
        п = Прогон(пара(20, "2026-11-01", "tu", {"tu": {"s": 20, "d": "2026-11-01"}}))
        п.маскот("kuku")
        п.вместе(*дни(2, 6))
        self.assertEqual(п.серия("kuku"), 5)
        п.маскот("tu")
        п.вместе("2026-11-07")
        self.assertEqual(п.серия("tu"), 21, "серия Ту стояла на паузе и продолжилась")
        self.assertEqual(п.пары, 26)
        self.assertNotIn("lost", п.карта()["tu"], "обрыва не было, возвращать нечего")

    def test_куку_тоже_ждёт_своего(self):
        п = Прогон(пара(20, "2026-11-01", "tu", {"tu": {"s": 20, "d": "2026-11-01"}}))
        п.маскот("kuku")
        п.вместе(*дни(2, 6))
        п.маскот("tu")
        п.вместе(*дни(7, 8))
        п.маскот("kuku")
        п.вместе("2026-11-09")
        self.assertEqual(п.серия("kuku"), 6)
        self.assertEqual(п.серия("tu"), 22)

    def test_долгая_пауза_при_живой_серии_пары(self):
        п = Прогон(пара(40, "2026-11-01", "tu", {"tu": {"s": 3, "d": "2026-10-10"}, "kuku": {"s": 22, "d": "2026-11-01"}}))
        п.вместе("2026-11-02")
        self.assertEqual(п.серия("tu"), 4)

    def test_пропуск_пары_рвёт_серию(self):
        # Пока стоял Куку, пара пропустила 04.11: пауза не спасает.
        п = Прогон(пара(20, "2026-11-01", "tu", {"tu": {"s": 20, "d": "2026-11-01"}}))
        п.маскот("kuku")
        п.вместе(*дни(2, 3))
        п.вместе(*дни(5, 6))
        п.маскот("tu")
        п.вместе("2026-11-07")
        self.assertEqual(п.серия("tu"), 1)
        self.assertEqual(п.карта()["tu"].get("lost"), 20, "обрыв записан, его можно вернуть")

    def test_день_маскота_раньше_серии_пары(self):
        # Ту последний раз считался до того, как началась нынешняя серия пары.
        п = Прогон(пара(3, "2026-11-01", "tu", {"tu": {"s": 9, "d": "2026-10-25"}}))
        п.вместе("2026-11-02")
        self.assertEqual(п.серия("tu"), 1)

    def test_обычный_день_без_смены(self):
        п = Прогон(пара(5, "2026-11-01", "tu", {"tu": {"s": 5, "d": "2026-11-01"}}))
        п.вместе("2026-11-02")
        self.assertEqual(п.серия("tu"), 6)


if __name__ == "__main__":
    unittest.main(verbosity=2)
