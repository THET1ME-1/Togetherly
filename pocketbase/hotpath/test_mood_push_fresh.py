# -*- coding: utf-8 -*-
"""Пуш о настроении только о свежей отметке: python3 pocketbase/hotpath/test_mood_push_fresh.py

Обращение 21.11.2026 (iPhone, Казахстан, партнёр в России): «партнёр
выбирает настроение, у меня приходит уведомление, открываю — а его нет, ни в
виджетах, ни в приложении, настроение только за предыдущий день». По базе:
отметка партнёра с временем 24.11 02:31 дошла до сервера 26.11 12:50 — телефон
двое суток не выходил на связь, очередь донесла её позже. Виджет такую
отметку правильно не взял (правило шести часов), а пуш «настроение дня»
ушёл, и человек открывал приложение ради настроения, которого сегодня нет.
"""
import importlib.util
import os

spec = importlib.util.spec_from_file_location(
    "hp", os.path.join(os.path.dirname(__file__), "hotpath.py"))
источник = open(spec.origin, encoding="utf-8").read()
начало = источник.index("РАСХОЖДЕНИЕ_ЧАСОВ_MS")
конец = источник.index("def _miss_you_push_text")
пространство: dict = {}
exec(compile(источник[начало:конец], "правило", "exec"), пространство)
нужен = пространство["пуш_о_настроении_нужен"]

СЕЙЧАС = 1_795_574_000_000          # 26.11.2026 ~12:33 UTC
МИН = 60_000
ЧАС = 60 * МИН
ok = True


def iso(мс: int) -> str:
    from datetime import datetime, timezone
    t = datetime.fromtimestamp(мс / 1000, tz=timezone.utc)
    return t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{t.microsecond:06d}Z"


def отметка(мс: int, **поля) -> dict:
    o = {"group_id": "g1", "user_uid": "u1", "label": "Устала",
         "image_path": "assets/images/mood_packs/bunny/tired.webp",
         "timestamp": iso(мс)}
    o.update(поля)
    return o


def проверить(имя: str, условие: bool) -> None:
    global ok
    print(("✓ " if условие else "✗ ") + имя)
    ok = ok and условие


проверить("отметка «сейчас» — пуш уходит", нужен(отметка(СЕЙЧАС - МИН), СЕЙЧАС))
проверить("из очереди через час — пуш уходит", нужен(отметка(СЕЙЧАС - ЧАС), СЕЙЧАС))
проверить("из очереди через двое суток — пуша нет (случай 26.11)",
          not нужен(отметка(СЕЙЧАС - 58 * ЧАС), СЕЙЧАС))
проверить("задним числом за вчера из календаря — пуша нет",
          not нужен(отметка(СЕЙЧАС - 24 * ЧАС), СЕЙЧАС))
проверить("без времени — пуша нет", not нужен(отметка(СЕЙЧАС, timestamp=""), СЕЙЧАС))

# Оба места, где сервер шлёт пуш о настроении, спрашивают правило до отправки.
for имя in ("async def _after_create(", "async def _after_update("):
    тело = источник[источник.index(имя):]
    тело = тело[:тело.index("\nasync def ", 10)] if "\nasync def " in тело[10:] else тело
    ветка = тело[тело.index('"mood"'):]
    проверить(f"{имя.split()[2][:-1]}: правило свежести стоит до пуша",
              "пуш_о_настроении_нужен(" in ветка
              and ветка.index("пуш_о_настроении_нужен(") < ветка.index("_notify_group("))

print("\nВСЁ ХОРОШО" if ok else "\nЕСТЬ ПРОБЛЕМЫ")
raise SystemExit(0 if ok else 1)
