#!/usr/bin/env python3
"""Готовый ответ каталога в памяти hotpath (19.10.2026).

Каталог приложение тянет целиком на каждом запуске, ответ один на всех, а
сборка в Python стоила 28 мс процессора на запрос против 16 у PocketBase.
Готовый ответ живёт 30 секунд: колонки времени правки у каталога нет, а
правят его руками и редко.

    python3 test_ready_cache.py
"""

from sqlite_read import ReadyCache

провалы = []


def проверить(имя, ok, подробно=""):
    print(("ОК   " if ok else "ПЛОХО") + f" {имя} {'' if ok else подробно}")
    if not ok:
        провалы.append(имя)


кэш = ReadyCache(ttl=30, limit=3)
проверить("пустой кэш промахивается", кэш.get("perPage=500", now=0) is None)
кэш.put("perPage=500", b'{"items":[]}', now=0)
проверить("тот же запрос в срок берёт готовое",
          кэш.get("perPage=500", now=29.9) == b'{"items":[]}')
проверить("другой запрос промахивается", кэш.get("perPage=50", now=1) is None)
проверить("после срока промах", кэш.get("perPage=500", now=30) is None)

кэш.put("perPage=500", b"new", now=40)
проверить("после срока ответ собирается заново", кэш.get("perPage=500", now=41) == b"new")

for i in range(10):
    кэш.put(f"page={i}", b"x", now=100)
проверить("случайные запросы не раздувают кэш", len(кэш) <= 3, f"ключей {len(кэш)}")
проверить("последний ответ на месте", кэш.get("page=9", now=100) == b"x")

print(f"\nпровалов: {len(провалы)}")
raise SystemExit(1 if провалы else 0)
