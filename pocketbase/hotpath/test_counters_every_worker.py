#!/usr/bin/env python3
"""Прибавки счётчиков пары сбрасывает в базу каждый рабочий процесс.

С 14.08.2026 hotpath работает в нескольких процессах, а фоновые задачи ведёт
один, тот, кому достался файловый замок. Прибавки `memories_count` и
`messages_count` при этом копит каждый процесс у себя, в своём словаре: процесс
без фоновой роли копил их и не сбрасывал никогда. До базы доходила малая часть,
ночной пересчёт выправлял цифру, и к вечеру всё повторялось. На 01.11.2026 у
244 пар с новыми воспоминаниями счётчик стоял на нуле, ещё у 1760 был занижен,
и достижения за воспоминания не открывались (обращение 553: «не отображается
количество воспоминаний»).

Запуск: python3 pocketbase/hotpath/test_counters_every_worker.py
"""
import unittest
from pathlib import Path

источник = (Path(__file__).parent / "hotpath.py").read_text(encoding="utf-8")
начало = источник.index("def _задачи_процесса(")
конец = источник.index("\n\n\n", начало)
среда: dict = {}
exec(источник[начало:конец], среда)
задачи_процесса = среда["_задачи_процесса"]


class ЗадачиПроцесса(unittest.TestCase):
    def test_счётчики_сбрасывает_и_процесс_без_фоновой_роли(self):
        self.assertIn("счётчики", задачи_процесса(фоновая_роль=False, пары="pg"))

    def test_остальное_фоновое_ведёт_один_процесс(self):
        self.assertEqual(задачи_процесса(фоновая_роль=False, пары="pg"), ["счётчики"])
        роль = задачи_процесса(фоновая_роль=True, пары="pg")
        self.assertIn("зеркало пар", роль)
        self.assertEqual(роль.count("счётчики"), 1)

    def test_пары_в_sqlite_пишет_только_один(self):
        # Каждый посторонний коммит в SQLite протухает снапшоты PocketBase:
        # там сброс остаётся за одним процессом.
        self.assertNotIn("счётчики", задачи_процесса(фоновая_роль=False, пары="sqlite"))
        self.assertIn("счётчики", задачи_процесса(фоновая_роль=True, пары="sqlite"))

    def test_сброс_идёт_по_порядку_пар(self):
        # Процессы пишут в одни и те же строки: в одном порядке они не
        # встанут друг другу поперёк в взаимной блокировке.
        тело = источник[источник.index("async def _flush_counters_pg("):источник.index("async def _counter_worker(")]
        self.assertIn("sorted(deltas.items())", тело)


if __name__ == "__main__":
    unittest.main()
