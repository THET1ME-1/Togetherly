/// draw_invite.js — правило частоты зова «пойдём порисовать».
///
/// Живёт отдельным модулем, потому что обработчики JSVM не видят функций уровня
/// файла: хук подключает это через `require`, а тест — через node.
///
/// Зов уходит сам, когда человек открывает раскраску. Без ограничения по
/// времени это лавина: за вечер в раскраску заходят десяток раз, и партнёр
/// получил бы десяток пушей. На «Скучаю» так и вышло — серия нажатий
/// превращалась в поток уведомлений, пока частоту не прижали.

/// Сколько молчим после отправленного зова.
const GAP_MS = 30 * 60 * 1000;

/// Можно ли звать сейчас. [lastMs] — когда звали в прошлый раз (0 или мусор
/// значит «никогда»).
function mayInvite(lastMs, nowMs, gapMs) {
  const gap = Number(gapMs);
  const now = Number(nowMs);
  const last = Number(lastMs);
  if (!isFinite(now) || now <= 0) return false;
  if (!isFinite(last) || last <= 0) return true;
  // Часы на сервере могли уйти назад — отметка из будущего не должна запирать
  // зов навсегда.
  if (last > now) return true;
  return now - last >= (isFinite(gap) && gap > 0 ? gap : GAP_MS);
}

module.exports = { mayInvite: mayInvite, GAP_MS: GAP_MS };
