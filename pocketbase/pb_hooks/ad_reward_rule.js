// Какой ролик платит монетами (роут /api/coins/ad-reward в coins.pb.js).
//
// Монеты и дневной счётчик «3 ролика за монеты» — только у кнопки
// «Посмотреть рекламу» в профиле. Остальные ролики (сундук, проба темы и фона,
// гардероб, подарки, возврат серии) дают свою награду и счётчик не трогают:
// иначе после сундука кнопка уже отвечала «лимит на сегодня» (отзыв
// 08.11.2026). Новые сборки шлют `purpose`; старые не шлют, и у них ролик за
// сундук узнаётся по номеру открытия, а остальное — как было.
function adRewardForCoins(body) {
  const b = body || {};
  if (b.purpose === 'coins') return true;
  if (b.purpose) return false;
  return !/^[a-z0-9]{15}$/.test(String(b.chestOpenId || ''));
}

module.exports = { adRewardForCoins };
