// Предпросмотр сезона (26.11.2026, владелец: «активируй новый год, только мне
// для теста»). Список аккаунтов лежит в pb_data/.season_preview.json —
// `{"<uid>": "ГГГГ-ММ-ДД"}`: для этих людей сервер живёт в указанный день.
// Сундук считает «сегодня» этим днём (сезон, игрушки), спрятанные вещи
// сезонных наборов разыгрываются и продаются им, приложение через
// /api/season/preview узнаёт день и включает свой календарь. Остальным ничего
// не меняется. Файл читается при каждом запросе: правка списка действует сразу,
// без перезапуска. Подключается `require(`${__hooks}/season_preview.js`)`.
module.exports = {
  // День предпросмотра для человека или "" — живёт по настоящему календарю.
  dayFor: (uid) => {
    if (!uid) return "";
    try {
      const raw = toString($os.readFile($app.dataDir() + "/.season_preview.json"));
      const list = JSON.parse(raw || "{}") || {};
      const d = String(list[uid] || "");
      return /^\d{4}-\d{2}-\d{2}$/.test(d) ? d : "";
    } catch (_) {
      return "";
    }
  },
};
