import 'package:flutter_test/flutter_test.dart';
import 'package:love_app/services/custom_wishes_store.dart';

/// Свои пожелания «Скучаю» жили только в prefs: переустановил приложение —
/// список пуст, зашёл со второго телефона — пусто там тоже. Человек заводит их
/// заново после каждого такого случая, а это ровно те слова, которые он
/// придумал для своей пары.
///
/// Теперь список едет на аккаунт (`users.miss_you_wishes`) — как сон маскотов
/// и свои темы. Правило слияния здесь: пустой ответ сервера локальный список НЕ
/// затирает, иначе пожелание, заведённое без сети, пропало бы на первом же
/// входе.
void main() {
  group('withWish', () {
    test('свежее встаёт первым', () {
      expect(withWish(const ['раз', 'два'], 'три'), ['три', 'раз', 'два']);
    });

    test('повтор поднимается, а не задваивается', () {
      expect(withWish(const ['раз', 'два'], 'два'), ['два', 'раз']);
    });

    test('регистр не плодит копий', () {
      expect(withWish(const ['Мой ангелочек'], 'мой ангелочек'),
          ['мой ангелочек']);
    });

    test('дальше трёх не растёт', () {
      final list = withWish(const ['раз', 'два', 'три'], 'четыре');
      expect(list, ['четыре', 'раз', 'два']);
    });

    test('пустая строка ничего не меняет', () {
      expect(withWish(const ['раз'], '   '), ['раз']);
    });
  });

  group('mergeCustomWishes', () {
    test('сервер знает список — он и главный', () {
      expect(
        mergeCustomWishes(local: const ['своё'], remote: const ['с сервера']),
        ['с сервера'],
      );
    });

    test('сервер молчит — держим своё', () {
      // null это «поле не приехало» (нет сети, старая сборка, отказ сервера).
      expect(mergeCustomWishes(local: const ['своё'], remote: null), ['своё']);
    });

    test('на сервере пусто, а у нас есть — не стираем', () {
      // Пожелание могли завести без сети: оно ещё не уехало на аккаунт.
      expect(
        mergeCustomWishes(local: const ['своё'], remote: const []),
        ['своё'],
      );
    });

    test('своего нет — берём серверное', () {
      expect(
        mergeCustomWishes(local: const [], remote: const ['а', 'б']),
        ['а', 'б'],
      );
    });

    test('лишнее с сервера обрезается до потолка', () {
      expect(
        mergeCustomWishes(
          local: const [],
          remote: const ['а', 'б', 'в', 'г', 'д'],
        ),
        ['а', 'б', 'в'],
      );
    });

    test('мусор в поле не роняет список', () {
      expect(
        mergeCustomWishes(local: const ['своё'], remote: const ['', '  ']),
        ['своё'],
      );
    });
  });
}
